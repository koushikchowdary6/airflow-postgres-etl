-- Schema definition. Safe to run repeatedly (every statement is IF NOT EXISTS),
-- which is what lets the DAG's first task be "ensure schema" rather than a
-- manual migration step.
--
-- Three schemas, separated by role:
--   staging   ephemeral, rebuilt every run
--   analytics durable, the tables people query
--   etl       pipeline control: watermark, batch audit, rejects

CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS analytics;
CREATE SCHEMA IF NOT EXISTS etl;

-- ---------------------------------------------------------------------------
-- Staging
-- ---------------------------------------------------------------------------

-- UNLOGGED: this table is truncated and rewritten on every run, so writing it
-- to the WAL buys nothing. It is not crash-safe and is not replicated, which
-- is exactly right for data that is one COPY away from being rebuilt. Never
-- use UNLOGGED for the durable tables below.
CREATE UNLOGGED TABLE IF NOT EXISTS staging.member_term_stage (
      congress              smallint      NOT NULL
    , bioguide_id           text          NOT NULL
    , start_date            date          NOT NULL
    , chamber               text          NOT NULL
    , state_abbrev          char(2)       NOT NULL
    , party_code            smallint      NOT NULL
    , party_label           text          NOT NULL
    , bioname               text          NOT NULL
    , birthday              date          NOT NULL
    , cumulative_congresses smallint      NOT NULL
    , cumulative_chamber    smallint      NOT NULL
    , age_days              integer       NOT NULL
    , age_years             numeric(9, 6) NOT NULL
    , generation            text          NOT NULL
    , source_row_number     integer       NOT NULL
);

-- ---------------------------------------------------------------------------
-- Analytics
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS analytics.member_term (
      member_term_id        bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    , congress              smallint      NOT NULL
    , bioguide_id           text          NOT NULL
    , start_date            date          NOT NULL
    , chamber               text          NOT NULL
    , state_abbrev          char(2)       NOT NULL
    , party_code            smallint      NOT NULL
    , party_label           text          NOT NULL
    , bioname               text          NOT NULL
    , birthday              date          NOT NULL
    , cumulative_congresses smallint      NOT NULL
    , cumulative_chamber    smallint      NOT NULL
    , age_days              integer       NOT NULL
    , age_years             numeric(9, 6) NOT NULL
    , generation            text          NOT NULL
    , first_loaded_at       timestamptz   NOT NULL DEFAULT now()
    , updated_at            timestamptz   NOT NULL DEFAULT now()

    -- The natural key. This single constraint is what makes the pipeline
    -- idempotent at the database level: even a buggy loader cannot create a
    -- duplicate business row, because the database refuses it. The upsert
    -- targets this constraint.
    , CONSTRAINT member_term_natural_key UNIQUE (congress, bioguide_id)

    -- Validation is enforced in Python *and* here. The Python checks give
    -- actionable per-row errors; these make the invariant true for anything
    -- that writes to the table, including a hand-written INSERT.
    , CONSTRAINT member_term_congress_range CHECK (congress BETWEEN 1 AND 150)
    , CONSTRAINT member_term_chamber_valid CHECK (chamber IN ('House', 'Senate'))
    , CONSTRAINT member_term_age_days_non_negative CHECK (age_days >= 0)
    , CONSTRAINT member_term_age_years_range CHECK (age_years BETWEEN 18 AND 105)
    , CONSTRAINT member_term_birthday_before_start CHECK (birthday < start_date)
);

-- Indexes are deliberately few: each one is paid for on every write.
--
-- The natural-key unique constraint already provides an index on
-- (congress, bioguide_id), which serves the upsert and any
-- "one Congress" lookup, so no separate index is created for those.

-- Serves the analytics model and the common "trend by chamber" query, which
-- group by chamber and order by congress.
CREATE INDEX IF NOT EXISTS member_term_chamber_congress_idx
    ON analytics.member_term (chamber, congress);

-- Serves "show me this member's whole career", which cannot use the natural-key
-- index because it does not know the congress.
CREATE INDEX IF NOT EXISTS member_term_bioguide_idx
    ON analytics.member_term (bioguide_id);

-- Aggregate model, rebuilt from the fact table on every run.
CREATE TABLE IF NOT EXISTS analytics.congress_age_summary (
      congress              smallint      NOT NULL
    , chamber               text          NOT NULL
    , member_count          integer       NOT NULL
    , mean_age_years        numeric(9, 4) NOT NULL
    , median_age_years      numeric(9, 4) NOT NULL
    , min_age_years         numeric(9, 4) NOT NULL
    , max_age_years         numeric(9, 4) NOT NULL
    , pct_aged_65_plus      numeric(6, 2) NOT NULL
    , median_change_vs_prev numeric(9, 4)
    , oldest_member         text          NOT NULL
    , built_at              timestamptz   NOT NULL DEFAULT now()
    , PRIMARY KEY (congress, chamber)
);

-- ---------------------------------------------------------------------------
-- Pipeline control
-- ---------------------------------------------------------------------------

-- Incremental position. One row per pipeline; `last_congress` is the highest
-- Congress successfully loaded AND verified.
CREATE TABLE IF NOT EXISTS etl.watermark (
      pipeline_name text        NOT NULL PRIMARY KEY
    , last_congress smallint    NOT NULL
    , updated_at    timestamptz NOT NULL DEFAULT now()
);

-- Audit trail: one row per run. Makes "what happened last night" answerable
-- with a query instead of by reading scheduler logs.
CREATE TABLE IF NOT EXISTS etl.batch_run (
      batch_id      text        NOT NULL PRIMARY KEY
    , pipeline_name text        NOT NULL
    , dag_run_id    text
    , status        text        NOT NULL
    , rows_read     integer
    , rows_staged   integer
    , rows_rejected integer
    , rows_inserted integer
    , rows_updated  integer
    , max_congress  smallint
    , started_at    timestamptz NOT NULL DEFAULT now()
    , finished_at   timestamptz
    , error_message text
    , CONSTRAINT batch_run_status_valid CHECK (status IN ('running', 'succeeded', 'failed'))
);

CREATE INDEX IF NOT EXISTS batch_run_started_idx ON etl.batch_run (started_at DESC);

-- Rejected input rows, kept so bad data is investigable after the fact rather
-- than only visible in a log line that has since rotated away.
CREATE TABLE IF NOT EXISTS etl.rejected_row (
      rejected_row_id   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    , batch_id          text        NOT NULL
    , source_row_number integer     NOT NULL
    , column_name       text        NOT NULL
    , raw_value         text
    , reason            text        NOT NULL
    , recorded_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS rejected_row_batch_idx ON etl.rejected_row (batch_id);
